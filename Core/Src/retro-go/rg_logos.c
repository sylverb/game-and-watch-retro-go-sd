static retro_logo_image** logo_image_cache;

/* Dynamic (core-provided) logos:
 * - registration stores blob location (deduped core_path + offset + size)
 * - decode cache is a 3-slot ring allocated from ITC (forgotten by itc_init
 *   when a core launches — see rg_reset_logo_buffers())
 *
 * Keep these tables small: they live in AHB .bss and eat the malloc heap. */
#define RG_LOGO_DYNAMIC_MAX        256  /* pad+header per system tab */
#define RG_LOGO_DYNAMIC_PATH_MAX    64  /* unique /cores/???.bin paths */
#define RG_LOGO_DYNAMIC_CACHE_SLOTS  3
#define RG_LOGO_DYNAMIC_CACHE_MAX_SIZE 8192

typedef struct
{
    uint8_t path_idx;
    uint32_t offset;
    uint32_t size;
} rg_dynamic_logo_blob_t;

static char dynamic_logo_paths[RG_LOGO_DYNAMIC_PATH_MAX][64];
static uint8_t dynamic_logo_path_count = 0;

static rg_dynamic_logo_blob_t dynamic_logo_blobs[RG_LOGO_DYNAMIC_MAX];
static int dynamic_logo_count = 0;

static int16_t dynamic_logo_cache_idx[RG_LOGO_DYNAMIC_CACHE_SLOTS];
static uint8_t *dynamic_logo_cache_buf[RG_LOGO_DYNAMIC_CACHE_SLOTS];
static int dynamic_logo_cache_next = 0;

static int dynamic_logo_path_intern(const char *core_path)
{
    for (uint8_t i = 0; i < dynamic_logo_path_count; i++) {
        if (strcmp(dynamic_logo_paths[i], core_path) == 0)
            return (int)i;
    }
    if (dynamic_logo_path_count >= RG_LOGO_DYNAMIC_PATH_MAX) {
        printf("rg_logos: dynamic logo path table full (%d)\n", RG_LOGO_DYNAMIC_PATH_MAX);
        return -1;
    }
    strncpy(dynamic_logo_paths[dynamic_logo_path_count], core_path,
            sizeof(dynamic_logo_paths[0]) - 1);
    dynamic_logo_paths[dynamic_logo_path_count][sizeof(dynamic_logo_paths[0]) - 1] = '\0';
    return (int)dynamic_logo_path_count++;
}

static bool dynamic_logo_cache_ensure(void)
{
    if (dynamic_logo_cache_buf[0])
        return true;
    for (int i = 0; i < RG_LOGO_DYNAMIC_CACHE_SLOTS; i++) {
        void *p = itc_malloc(RG_LOGO_DYNAMIC_CACHE_MAX_SIZE);
        if (p == (void *)0xffffffff) {
            printf("rg_logos: ITC cache alloc failed\n");
            for (int j = 0; j < i; j++)
                dynamic_logo_cache_buf[j] = NULL;
            return false;
        }
        dynamic_logo_cache_buf[i] = (uint8_t *)p;
        dynamic_logo_cache_idx[i] = RG_LOGO_EMPTY;
    }
    return true;
}

void rg_reset_logo_buffers() {
    logo_image_cache = NULL;
    dynamic_logo_count = 0;
    dynamic_logo_path_count = 0;
    for (int i = 0; i < RG_LOGO_DYNAMIC_CACHE_SLOTS; i++) {
        dynamic_logo_cache_idx[i] = RG_LOGO_EMPTY;
        /* itc_init() already forgot the bump; drop dangling pointers. */
        dynamic_logo_cache_buf[i] = NULL;
    }
    dynamic_logo_cache_next = 0;
}

int16_t rg_register_dynamic_logo_blob(const char *core_path, uint32_t offset, uint32_t size)
{
    if (!core_path)
        return RG_LOGO_EMPTY;
    if (size < sizeof(retro_logo_image) || size > RG_LOGO_DYNAMIC_CACHE_MAX_SIZE)
        return RG_LOGO_EMPTY;
    if (dynamic_logo_count >= RG_LOGO_DYNAMIC_MAX) {
        printf("rg_logos: dynamic logo registry full (%d)\n", RG_LOGO_DYNAMIC_MAX);
        return RG_LOGO_EMPTY;
    }

    int path_idx = dynamic_logo_path_intern(core_path);
    if (path_idx < 0)
        return RG_LOGO_EMPTY;

    rg_dynamic_logo_blob_t *b = &dynamic_logo_blobs[dynamic_logo_count];
    b->path_idx = (uint8_t)path_idx;
    b->offset = offset;
    b->size = size;

    /* Return negative indices:
     * RG_LOGO_EMPTY=-1 stays reserved, so slot 0 uses -2, slot 1 uses -3, ... */
    int16_t idx = (int16_t)(-2 - dynamic_logo_count);
    dynamic_logo_count++;
    return idx;
}

retro_logo_image *rg_get_logo(int16_t logo_index) {
    uint8_t header[4];
    uint16_t width, height;
    size_t read;

    if (logo_index == RG_LOGO_EMPTY)
        return NULL;
    if (logo_index < 0) {
        int slot = (-2 - logo_index);
        if (slot < 0 || slot >= dynamic_logo_count)
            return NULL;

        if (!dynamic_logo_cache_ensure())
            return NULL;

        /* Cache hit? */
        for (int i = 0; i < RG_LOGO_DYNAMIC_CACHE_SLOTS; i++) {
            if (dynamic_logo_cache_idx[i] == logo_index)
                return (retro_logo_image *)dynamic_logo_cache_buf[i];
        }

        /* Cache miss: evict a slot and re-load blob into it. */
        int cache_slot = dynamic_logo_cache_next;
        dynamic_logo_cache_next = (dynamic_logo_cache_next + 1) % RG_LOGO_DYNAMIC_CACHE_SLOTS;
        dynamic_logo_cache_idx[cache_slot] = RG_LOGO_EMPTY;

        const rg_dynamic_logo_blob_t *blob = &dynamic_logo_blobs[slot];
        FILE *file = fopen(dynamic_logo_paths[blob->path_idx], "rb");
        if (!file)
            return NULL;
        if (fseek(file, (long)blob->offset, SEEK_SET) != 0) {
            fclose(file);
            return NULL;
        }

        read = fread(dynamic_logo_cache_buf[cache_slot], 1, (size_t)blob->size, file);
        fclose(file);
        if (read != (size_t)blob->size)
            return NULL;

        dynamic_logo_cache_idx[cache_slot] = logo_index;
        return (retro_logo_image *)dynamic_logo_cache_buf[cache_slot];
    }

    // Logos always included in internal flash.
    // Must be at beginning of the logo list.
    switch (logo_index) {
        case RG_LOGO_RGO:
            return (retro_logo_image *)&logo_rgo;
        case RG_LOGO_RGW:
            return (retro_logo_image *)&logo_rgw;
        case RG_LOGO_GNW:
            return (retro_logo_image *)&logo_gnw;
    }

    static_assert(INT_LOGO_COUNT == 3);
    logo_index -= INT_LOGO_COUNT;

    if (logo_image_cache != NULL) {
        return logo_image_cache[logo_index];
    }

    FILE* file = fopen("/bios/logo.bin", "rb");
    if (!file) {
        printf("Error: unable to open logo file\n");
        return NULL;
    }

    logo_image_cache = itc_malloc(MAX_LOGO_COUNT * sizeof(retro_logo_image*));
    assert(logo_image_cache != (void *)0xffffffff);

    int current_logo_index = 0;
    while (1) {
        if (fread(header, 1, 4, file) != 4)
            break;

        width = (uint16_t)(header[0] | ((uint16_t)header[1] << 8));
        height = (uint16_t)(header[2] | ((uint16_t)header[3] << 8));

        size_t data_size = ((width + 7) >> 3) * height; // width aligned to 8 * height / 8
        data_size = (data_size + 3) & ~3; // align to 4 bytes

        retro_logo_image* dest = itc_malloc(sizeof(retro_logo_image) + data_size);
        assert(dest != (void *)0xffffffff);
        dest->width = width;
        dest->height = height;
        read = fread(dest->logo, 1, data_size, file);
        if (read == 0) break;

        logo_image_cache[current_logo_index] = dest;
        current_logo_index++;
    }

    fclose(file);
    return logo_image_cache[logo_index];
}

